"""Контракт відповіді помічника: що саме модель має повернути і як це
перевіряється.

Окремий модуль навмисно. Схема — це домовленість між моделлю і рештою
застосунку, і вона не залежить від провайдера: змінивши модель або спосіб
виклику, схему ви не змінюєте. Веб-рівень і сторінка працюють лише з тим,
що пройшло перевірку тут.

Що потрібно решті застосунку від відповіді (розділ 2 практичної роботи):

* текст відповіді для клієнта;
* тема звернення з фіксованого переліку — за нею звернення передається
  потрібному відділу;
* чи відповідь ґрунтується на правилах, чи правила про це мовчать;
* чи потрібне уточнення;
* чи передати розмову оператору;
* номер замовлення, якщо клієнт його назвав (формат — у `context.md`).

Як назвати поля, які з них обовʼязкові, які з переліком значень, які
можуть бути порожніми — ваше рішення. Як і те, чим описати схему: JSON
Schema вручну (перевірка — пакет `jsonschema`) або pydantic-модель, з
якої схема генерується (перевірка — та сама модель).

Сторінка каркаса бере текст для клієнта з поля `reply`, а решту полів
показує як картку звернення. Назвете інакше — змініть сторінку.
"""
import json
from pydantic import BaseModel, Field, ValidationError

class AssistantResponse(BaseModel):
    """Схема відповіді помічника."""
    reply: str = Field(..., description="Текст відповіді для клієнта українською мовою.")
    topic: str = Field(..., description="Тема звернення. Перелік: 'Замовлення', 'Доставка', 'Оплата', 'Повернення', 'Гарантія', 'Інше'.")
    based_on_rules: bool = Field(..., description="Чи відповідь повністю ґрунтується на правилах магазину.")
    needs_clarification: bool = Field(..., description="Чи потрібне уточнення інформації від клієнта.")
    transfer_to_operator: bool = Field(..., description="Чи потрібно передати розмову оператору (наприклад, якщо проблема складна або виходить за межі правил).")
    order_number: str | None = Field(default=None, description="Номер замовлення (6 цифр), якщо клієнт його назвав.")

def output_schema() -> dict:
    """Повернути JSON Schema відповіді помічника.
    
    Ця сама схема передається моделі як опис очікуваного результату
    (через `response_format` або текстом в інструкції) і використовується
    для перевірки того, що повернулося.
    """
    return AssistantResponse.model_json_schema()


def validate(raw: str) -> dict:
    """Перевірити сиру відповідь моделі й повернути дані, яким можна
    довіряти структурно.

    На вході — текст, який повернула модель. На виході — обʼєкт, що
    відповідає схемі. Якщо текст не є JSON або не проходить схему —
    підняти помилку з поясненням, що саме не так: цей текст стане в
    пригоді, якщо ви вирішите повторити запит із ним.

    Схема перевіряє форму, а не зміст. Що ще варто перевірити кодом —
    наприклад, чи справді названий номер замовлення зустрічається в
    розмові — вирішуєте ви.
    """
    try:
        data = json.loads(raw)
        validated_model = AssistantResponse.model_validate(data)
        return validated_model.model_dump()
    except json.JSONDecodeError:
        raise ValueError("Модель повернула невалідний JSON.")
    except ValidationError as e:
        raise ValueError(f"Відповідь моделі не відповідає схемі: {e}")
